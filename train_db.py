def clean_check(y_true, y_pred, channels, n_classes, out_dir, results):
    """
    CHECK 1 -- clean data: does the model leave untouched tiles alone?

    Runs on the label == 0 subset of the test region: real CPI tiles that drew
    zero bands and were therefore never modified. The correct answer for every
    one of them is knee = 0, so the only thing being measured here is the
    false-positive rate.

    Reported per channel because HH and HV have very different backscatter
    floors, and a model can easily be clean-safe on one while triggering
    constantly on the other -- an aggregate number would average that away.

    Also records WHERE the false positives land: a model that mostly errs to
    knee@1 is far healthier than one that errs to knee@6.

    Args:
        y_true, y_pred (np.ndarray): (N,) over the FULL test set.
        channels (np.ndarray): (N,) channel name per tile.
        n_classes (int): label space size.
        out_dir (str): output directory.
        results (dict): mutated in place with the clean metrics.
    """
    clean = (y_true == 0)

    if not clean.any():
        print("\n=== CHECK 1: CLEAN DATA ===")
        print("  SKIPPED: the test set contains no clean tiles. It should have been "
              "generated with --min-bands 0 so clean tiles stay interspersed.")
        results['clean_recall'] = float('nan')
        results['false_positive_rate'] = float('nan')
        return

    pred_clean = y_pred[clean]
    n = int(clean.sum())

    recall = float(np.mean(pred_clean == 0))
    fpr = float(np.mean(pred_clean > 0))

    per_channel = {}
    for ch in sorted(set(channels.tolist())):
        sel = clean & (channels == ch)
        if sel.any():
            per_channel[ch] = {
                'n': int(sel.sum()),
                'clean_recall': float(np.mean(y_pred[sel] == 0)),
                'false_positive_rate': float(np.mean(y_pred[sel] > 0)),
            }

    fp_counts = np.bincount(pred_clean[pred_clean > 0], minlength=n_classes)[:n_classes]
    fp_dist = {str(k): int(v) for k, v in enumerate(fp_counts) if k > 0 and v > 0}

    results['clean_n'] = n
    results['clean_recall'] = recall
    results['false_positive_rate'] = fpr
    results['clean_per_channel'] = per_channel
    results['clean_false_positive_distribution'] = fp_dist

    print("\n=== CHECK 1: CLEAN DATA (unmodified tiles, knee = 0) ===")
    print(f"  N clean tiles  : {n}")
    print(f"  Clean recall   : {recall:.4f}   <- fraction correctly called clean")
    print(f"  False positives: {fpr:.4f}")
    for ch, s in per_channel.items():
        print(f"    {ch}: recall={s['clean_recall']:.4f}  FPR={s['false_positive_rate']:.4f}  "
              f"(n={s['n']})")
    if fp_dist:
        print("  False positives land on: "
              + ", ".join(f"knee@{k}:{v}" for k, v in fp_dist.items()))

    save_clean_check_png(pred_clean, channels[clean], n_classes, out_dir)


def contaminated_check(y_true, y_pred, channels, jsr, n_classes, out_dir, results):
    """
    CHECK 2 -- contaminated data: does the model count the bands correctly?

    Runs on the label > 0 subset of the test region. Reports the counting task
    (exact / tol-1 knee accuracy) and the detection task (contaminated called
    contaminated at all) separately, because a model can be a strong detector
    while still confusing adjacent knee counts -- and only the detection number
    matters if the downstream use is "flag this CPI for mitigation".

    Per-class rows include called_clean, the miss mode that actually hurts: an
    RFI tile silently passed through as clean.

    Args:
        y_true, y_pred (np.ndarray): (N,) over the FULL test set.
        channels (np.ndarray): (N,) channel name per tile.
        jsr (np.ndarray|None): (N, max_bands) realized per-band JSR.
        n_classes (int): label space size.
        out_dir (str): output directory.
        results (dict): mutated in place with the contaminated metrics.
    """
    rfi = (y_true > 0)

    if not rfi.any():
        print("\n=== CHECK 2: CONTAMINATED DATA ===")
        print("  SKIPPED: the test set contains no contaminated tiles.")
        return

    exact = float(np.mean(y_pred[rfi] == y_true[rfi]))
    tol1 = float(np.mean(np.abs(y_pred[rfi] - y_true[rfi]) <= 1))
    detection = float(np.mean(y_pred[rfi] > 0))
    missed = float(np.mean(y_pred[rfi] == 0))

    per_class = {}
    for k in range(1, n_classes):
        sel = (y_true == k)
        if sel.any():
            per_class[str(k)] = {
                'n': int(sel.sum()),
                'recall': float(np.mean(y_pred[sel] == k)),
                'tol1': float(np.mean(np.abs(y_pred[sel] - k) <= 1)),
                'called_clean': float(np.mean(y_pred[sel] == 0)),
            }

    per_channel = {}
    for ch in sorted(set(channels.tolist())):
        sel = rfi & (channels == ch)
        if sel.any():
            per_channel[ch] = {
                'n': int(sel.sum()),
                'exact_acc': float(np.mean(y_pred[sel] == y_true[sel])),
                'tol1_acc': float(np.mean(np.abs(y_pred[sel] - y_true[sel]) <= 1)),
                'detection_rate': float(np.mean(y_pred[sel] > 0)),
            }

    results['rfi_n'] = int(rfi.sum())
    results['exact_rfi'] = exact
    results['tol1_rfi'] = tol1
    results['detection_rate'] = detection
    results['missed_as_clean'] = missed
    results['rfi_per_class'] = per_class
    results['rfi_per_channel'] = per_channel

    print(f"\n=== CHECK 2: CONTAMINATED DATA (knee 1..{n_classes - 1}) ===")
    print(f"  N RFI tiles    : {int(rfi.sum())}")
    print(f"  Exact knee acc : {exact:.4f}")
    print(f"  Tol-1 knee acc : {tol1:.4f}")
    print(f"  Detection rate : {detection:.4f}   <- called contaminated at all")
    print(f"  Missed as clean: {missed:.4f}")
    for k, s in per_class.items():
        print(f"    knee@{k}: recall={s['recall']:.3f}  tol1={s['tol1']:.3f}  "
              f"called clean={s['called_clean']:.3f}  (n={s['n']})")
    for ch, s in per_channel.items():
        print(f"    {ch}: exact={s['exact_acc']:.4f}  tol1={s['tol1_acc']:.4f}  "
              f"detection={s['detection_rate']:.4f}")

    save_accuracy_vs_jsr_png(y_true, y_pred, jsr, out_dir)


def diagonal_jump_check(data, out_dir, results):
    """
    Population-level SCM-diagonal jump check on a standard test region:
    clean tiles (label 0) vs. contaminated tiles (label > 0), NOT necessarily
    the same background pair-for-pair -- that stronger check is
    paired_behavior_check, run on --paired-test-dir instead.

    This is a non-ML companion signal: RFI should produce a much larger
    adjacent-row jump on the diagonal than a clean tile's comparatively flat
    profile.

    Args:
        data (dict): output of load_rfi_data_dir on the test region.
        out_dir (str): output directory.
        results (dict): mutated in place with the jump metrics.
    """
    y_true = data['labels']
    jump = data['diag_jump_db']

    clean_sel = (y_true == 0) & np.isfinite(jump)
    contam_sel = (y_true > 0) & np.isfinite(jump)

    if not clean_sel.any() or not contam_sel.any():
        print("\n=== DIAGONAL JUMP CHECK (population-level) ===")
        print("  SKIPPED: not enough finite jump values on one side (clean/contaminated).")
        return

    jump_clean = jump[clean_sel]
    jump_contam = jump[contam_sel]
    threshold = float(np.percentile(jump_clean, 95))
    jump_detection_rate = float(np.mean(jump_contam > threshold))

    results['test_diag_jump_clean_mean_db'] = float(np.mean(jump_clean))
    results['test_diag_jump_clean_median_db'] = float(np.median(jump_clean))
    results['test_diag_jump_contam_mean_db'] = float(np.mean(jump_contam))
    results['test_diag_jump_contam_median_db'] = float(np.median(jump_contam))
    results['test_diag_jump_threshold_db'] = threshold
    results['test_diag_jump_detection_rate'] = jump_detection_rate

    print("\n=== DIAGONAL JUMP CHECK (population-level, test region) ===")
    print(f"  N clean={int(clean_sel.sum())}  N contaminated={int(contam_sel.sum())}")
    print(f"  clean  jump (dB): mean={np.mean(jump_clean):.2f}  median={np.median(jump_clean):.2f}")
    print(f"  contam jump (dB): mean={np.mean(jump_contam):.2f}  median={np.median(jump_contam):.2f}")
    print(f"  threshold (95th pct of clean) = {threshold:.2f} dB "
          f"-> flags {jump_detection_rate:.4f} of contaminated tiles on the "
          f"diagonal jump ALONE, no model involved")

    save_diagonal_jump_hist_png(jump_clean, jump_contam, threshold, out_dir,
                                filename='diagonal_jump_hist_testregion.png',
                                title_suffix=' (test region, not necessarily paired)')


def paired_behavior_check(model, paired_data, out_dir, results):
    """
    "Examine the behavior": the SAME background mountain tile, once left
    clean and once with RFI forced onto it (generate_mountain_rfi_data.py
    --paired-test). Because both halves share one background, this directly
    measures whether adding RFI flips the model's call on that exact tile,
    rather than comparing across two different tiles that happened to draw
    different band counts.

    Also reports the SCM-diagonal jump metric on the same pairs, as an
    independent, non-ML companion signal.

    Args:
        model: trained Keras model.
        paired_data (dict): output of load_paired_test_dir.
        out_dir (str): output directory.
        results (dict): mutated in place with the paired metrics.

    Returns:
        results (dict)
    """
    clean = paired_data['clean']
    contam = paired_data['contam']
    n_pairs = len(clean['labels'])

    print(f"\n=== PAIRED CHECK: SAME-TILE CLEAN vs. RFI-OVERLAID (n={n_pairs} pairs) ===")

    if n_pairs == 0:
        print("  SKIPPED: no matched pairs in the paired test set.")
        return results

    pred_clean = np.argmax(
        model.predict([clean['eigen'], clean['global']], verbose=0), axis=-1
    )
    pred_contam = np.argmax(
        model.predict([contam['eigen'], contam['global']], verbose=0), axis=-1
    )
    y_true_contam = contam['labels']

    clean_recall = float(np.mean(pred_clean == 0))
    exact_contam = float(np.mean(pred_contam == y_true_contam))
    tol1_contam = float(np.mean(np.abs(pred_contam - y_true_contam) <= 1))
    detection_rate = float(np.mean(pred_contam > 0))
    joint_rate = float(np.mean((pred_clean == 0) & (pred_contam > 0)))

    results['paired_n'] = int(n_pairs)
    results['paired_clean_recall'] = clean_recall
    results['paired_exact_acc'] = exact_contam
    results['paired_tol1_acc'] = tol1_contam
    results['paired_detection_rate'] = detection_rate
    results['paired_joint_success_rate'] = joint_rate

    print(f"  Clean-side recall      : {clean_recall:.4f}   <- same tile, untouched")
    print(f"  Contaminated exact acc : {exact_contam:.4f}   <- same tile, RFI forced onto it")
    print(f"  Contaminated tol-1 acc : {tol1_contam:.4f}")
    print(f"  Contaminated detection : {detection_rate:.4f}")
    print(f"  Joint success (both)   : {joint_rate:.4f}   <- clean stayed clean AND RFI "
          f"got flagged, on the SAME background")

    jump_clean = diagonal_jump_metric(clean['diagonal'], clean['diag_valid_idx'])
    jump_contam = diagonal_jump_metric(contam['diagonal'], contam['diag_valid_idx'])

    finite_clean = jump_clean[np.isfinite(jump_clean)]
    finite_contam = jump_contam[np.isfinite(jump_contam)]

    if len(finite_clean) and len(finite_contam):
        threshold = float(np.percentile(finite_clean, 95))
        jump_detection_rate = float(np.mean(finite_contam > threshold))

        results['diag_jump_clean_mean_db'] = float(np.mean(finite_clean))
        results['diag_jump_clean_median_db'] = float(np.median(finite_clean))
        results['diag_jump_contam_mean_db'] = float(np.mean(finite_contam))
        results['diag_jump_contam_median_db'] = float(np.median(finite_contam))
        results['diag_jump_threshold_db'] = threshold
        results['diag_jump_detection_rate'] = jump_detection_rate

        print(f"\n  SCM diagonal jump metric (dB, max adjacent step over valid rows), "
              f"SAME tiles as above:")
        print(f"    clean  : mean={np.mean(finite_clean):.2f}  median={np.median(finite_clean):.2f}")
        print(f"    contam : mean={np.mean(finite_contam):.2f}  median={np.median(finite_contam):.2f}")
        print(f"    threshold (95th pct of clean) = {threshold:.2f} dB "
              f"-> flags {jump_detection_rate:.4f} of contaminated tiles on the "
              f"diagonal jump ALONE, no model involved")

        save_diagonal_jump_hist_png(finite_clean, finite_contam, threshold, out_dir,
                                    filename='diagonal_jump_hist_paired.png',
                                    title_suffix=' (paired, same tile)')
    else:
        print("  Diagonal jump metric: not enough finite values to report.")

    save_paired_behavior_png(results, out_dir)

    return results


def evaluate(model, data, n_classes, run_name, out_dir):
    """
    Evaluate on the held-out test region, as TWO explicit checks.

    The test set contains both kinds of tile -- clean ones are simply those that
    drew 0 bands -- so a single forward pass covers both, and the two checks are
    two views of the same predictions:

        CHECK 1  clean data        -> can it leave untouched tiles alone?
        CHECK 2  contaminated data -> can it count the bands?

    The confusion matrix spans the full 0..n_classes grid, so both checks are
    also visible there: row 0 is the clean check, rows 1..6 the contaminated one.

    Args:
        model: trained Keras model.
        data (dict): output of load_rfi_data_dir on the test dir.
        n_classes (int): label space size, taken from the TRAINING set.
        run_name (str): used in figure titles.
        out_dir (str): output directory.

    Returns:
        results (dict)
    """
    y_true = data['labels']
    y_pred = np.argmax(model.predict([data['eigen'], data['global']], verbose=0),
                       axis=-1)
    channels = data['channels']

    results = {
        'run': run_name,
        'n_test': int(len(y_true)),
        'n_keep': N_KEEP,
        'n_classes': n_classes,
        'test_pulse_window': data['meta'].get('pulse_window'),
        # Overall, across clean and contaminated together
        'exact_acc': float(np.mean(y_pred == y_true)),
        'tol1_acc': float(np.mean(np.abs(y_pred - y_true) <= 1)),
    }

    print(f"\n{'='*60}")
    print(f"HELD-OUT TEST REGION  pulses {data['meta'].get('pulse_window')}")
    print(f"  N tiles: {len(y_true)}   features: top {N_KEEP} eigenvalues")
    print(f"  Overall exact: {results['exact_acc']:.4f}   "
          f"tol-1: {results['tol1_acc']:.4f}")
    print(f"{'='*60}")

    clean_check(y_true, y_pred, channels, n_classes, out_dir, results)
    contaminated_check(y_true, y_pred, channels, data['jsr'], n_classes,
                       out_dir, results)
    diagonal_jump_check(data, out_dir, results)

    print("\n  Saving confusion matrix and metrics ...")
    save_confusion_matrix_png(
        y_true, y_pred, n_classes, out_dir,
        f"Knee Confusion Matrix -- held-out region "
        f"(pulses {data['meta'].get('pulse_window')})\n"
        f"row 0 = clean check, rows 1+ = contaminated check",
    )
    save_metrics_png(results, out_dir)

    return results


