def _glob_tile_files(data_dir):
    """
    Non-paired tile-record files in a directory: either the generic
    real-background naming (rfi_data_<freq>_<pol>.h5, written by
    generate_rfi_data.py / generate_amazon_data.py) or the mountain naming
    (mountain_rfi_data_<freq>_<pol>.h5, written by
    generate_mountain_rfi_data.py). Paired test files
    (mountain_rfi_data_paired_*.h5) are excluded -- those are loaded
    separately by load_paired_test_dir, since they need pair matching rather
    than a flat concatenation.
    """
    found = set()
    for pattern in TILE_FILE_PATTERNS:
        found.update(glob.glob(os.path.join(data_dir, pattern)))
    found -= set(glob.glob(os.path.join(data_dir, PAIRED_FILE_PATTERN)))
    return sorted(found)


def load_rfi_data_dir(data_dirs, max_samples=None, tag=''):
    """
    Load every tile-record file from one or more directories, concatenating
    them into a single pool. Accepts either naming family (see
    _glob_tile_files), so an Amazon run and a mountain run can be passed
    together and trained on as one combined set.

    Each channel got an independent RFI injection realization, so labels are
    uncorrelated even where two channels share a physical background. Clean
    tiles (knee = 0) are already interspersed through these files; there is
    no separate clean source.

    The SCM diagonal and its per-index validity mask are required in every
    source file (both generators write them); a file missing either dataset
    raises an error rather than being silently degraded.

    Args:
        data_dirs (str or list[str]): one or more directories to load.
        max_samples (int|None): Cap on tiles loaded per file (evenly strided).
        tag (str): Label used in the printout (e.g. 'TRAIN region').

    Returns:
        data (dict) with keys:
            eigen (N, N_KEEP, 2) float32
            global (N, N_GLOBAL) float32
            labels (N,) int32          -- knee = number of injected bands, 0 = clean
            groups (N,) int64          -- source-namespaced tile_pulse, the block-split key
            channels (N,) object       -- 'A-HH' / 'A-HV' / ...
            jsr (N, max_bands) float32 or None -- NaN-padded per-band JSR
            diagonal (N, M) float32    -- linear scale, NaN where unavailable
            diag_valid_idx (N, M) bool -- all False where unavailable
            diag_jump_db (N,) float32  -- diagonal_jump_metric()
            n_classes (int)
            meta (dict)
    """
    if isinstance(data_dirs, str):
        data_dirs = [data_dirs]

    eigen_parts, global_parts = [], []
    label_parts, group_parts, chan_parts, jsr_parts = [], [], [], []
    diag_parts, diag_valid_parts = [], []
    n_classes = 0
    meta = {'dirs': list(data_dirs), 'files': [], 'channels': [], 'pulse_window': None}

    print(f"\nLoading {tag or data_dirs} ...")

    for source_id, data_dir in enumerate(data_dirs):
        paths = _glob_tile_files(data_dir)
        if not paths:
            raise FileNotFoundError(
                f"No tile record files (rfi_data_*.h5 / mountain_rfi_data_*.h5) "
                f"found in {data_dir}"
            )

        for path in paths:
            with h5py.File(path, 'r') as f:
                n_rec = int(f.attrs.get('n_records', f['labels'].shape[0]))
                freq = str(f.attrs.get('frequency', '?'))
                pol = str(f.attrs.get('polarization', '?'))
                chan = f'{freq}-{pol}'

                odr = float(f.attrs.get('off_diag_overlap_ratio', float('nan')))
                dvr = float(f.attrs.get('diag_valid_ratio', float('nan')))
                gap = bool(f.attrs.get('gap_exclusion_used', False))
                seed = int(f.attrs.get('seed', -1))
                p0 = int(f.attrs.get('pulse_start', -1)) if 'pulse_start' in f.attrs else -1
                p1 = int(f.attrs.get('pulse_end', -1)) if 'pulse_end' in f.attrs else -1
                min_b = int(f.attrs.get('min_bands', -1))
                max_b = int(f.attrs.get('max_bands', -1))

                if 'diagonal' not in f or 'diag_valid_idx' not in f:
                    raise ValueError(
                        f"{path} has no 'diagonal'/'diag_valid_idx' dataset. "
                        f"Regenerate it with the current generate_amazon_data.py "
                        f"/ generate_mountain_rfi_data.py, both of which write these."
                    )

                sel = slice(None)
                if max_samples is not None and n_rec > max_samples:
                    stride = int(np.ceil(n_rec / max_samples))
                    sel = slice(0, n_rec, stride)

                eigvals = f['eigenvalues'][sel]              # (n, M) linear, descending
                labels = f['labels'][sel].astype(np.int32)
                groups_raw = f['tile_pulse'][sel].astype(np.int64)
                jsr = np.asarray(f['jsr_db'][sel], dtype=np.float32) if 'jsr_db' in f else None

                diag = np.asarray(f['diagonal'][sel], dtype=np.float64)
                diag_valid = np.asarray(f['diag_valid_idx'][sel], dtype=bool)

                eigen, global_ = features_from_eigenvalues(eigvals)

                eigen_parts.append(eigen)
                global_parts.append(global_)
                label_parts.append(labels)
                group_parts.append(source_id * GROUP_OFFSET + groups_raw)
                chan_parts.append(np.full(len(labels), chan, dtype=object))
                diag_parts.append(diag)
                diag_valid_parts.append(diag_valid)
                if jsr is not None:
                    jsr_parts.append(jsr)

                n_classes = max(n_classes, int(f.attrs.get('n_classes', 0)))

                print(f"  {os.path.basename(path)}: {len(labels)} tiles  "
                      f"[{chan}, pulses {p0}-{p1}, bands {min_b}..{max_b}, seed={seed}, "
                      f"gap={gap}, off_diag={odr:.2f}, diag={dvr:.2f}]")

                if min_b != 0:
                    print(f"    WARNING: min_bands={min_b}, so this set has NO clean tiles. "
                          f"Training/test sources should be generated with --min-bands 0 so "
                          f"clean data stays interspersed in the same distribution.")

                if gap and not (np.isclose(odr, EXPECTED_OFF_DIAG_OVERLAP_RATIO)
                                and np.isclose(dvr, EXPECTED_DIAG_VALID_RATIO)):
                    print(f"    NOTE: SCM validity ratios differ from the permissive "
                          f"target ({EXPECTED_OFF_DIAG_OVERLAP_RATIO}/"
                          f"{EXPECTED_DIAG_VALID_RATIO}). Dithered CPIs may have had "
                          f"SCM entries zeroed at generation time.")

                meta['files'].append(os.path.basename(path))
                if chan not in meta['channels']:
                    meta['channels'].append(chan)
                if p0 != -1:
                    meta['pulse_window'] = [p0, p1]
                meta['seed'] = seed
                meta['min_bands'] = min_b
                meta['max_bands'] = max_b
                meta['off_diag_overlap_ratio'] = odr
                meta['diag_valid_ratio'] = dvr

    labels = np.concatenate(label_parts, axis=0)
    diag_lin = np.concatenate(diag_parts, axis=0)
    diag_valid_idx = np.concatenate(diag_valid_parts, axis=0)

    diag_jump_db = diagonal_jump_metric(diag_lin, diag_valid_idx)

    return {
        'eigen': np.concatenate(eigen_parts, axis=0),
        'global': np.concatenate(global_parts, axis=0),
        'labels': labels,
        'groups': np.concatenate(group_parts, axis=0),
        'channels': np.concatenate(chan_parts, axis=0),
        'jsr': np.concatenate(jsr_parts, axis=0) if jsr_parts else None,
        'diagonal': diag_lin.astype(np.float32),
        'diag_valid_idx': diag_valid_idx,
        'diag_jump_db': diag_jump_db,
        'n_classes': n_classes or int(labels.max()) + 1,
        'meta': meta,
    }


def check_disjoint(train_meta, test_meta):
    """
    Confirm the test window does not overlap the training window.

    A shared pulse would mean a test tile's background was seen in training,
    which is what the separate-region design exists to prevent.
    """
    tp = train_meta.get('pulse_window')
    xp = test_meta.get('pulse_window')
    if not tp or not xp or -1 in tp or -1 in xp:
        return

    overlap = min(tp[1], xp[1]) - max(tp[0], xp[0])
    if overlap > 0:
        print(f"\n  WARNING: test window {xp} overlaps the training window {tp} by "
              f"{overlap} pulses. Those tiles' backgrounds were seen in training; "
              f"the held-out metrics will be optimistic.")
    else:
        print(f"  test pulses {xp} disjoint from training {tp}  OK")

    if test_meta.get('seed') == train_meta.get('seed'):
        print(f"  NOTE: the test set was generated with the same --seed as the "
              f"training set. The per-tile injection stream is keyed on the "
              f"WINDOW-RELATIVE pulse tile, so the two sets replay the same band "
              f"counts/rows/JSRs tile-for-tile. Backgrounds still differ, so this "
              f"is not label leakage, but a distinct seed gives a genuinely "
              f"independent injection realization.")


def split_train_val(groups, val_frac, buffer_tiles):
    """
    Split the training region into train / val by CONTIGUOUS pulse-tile blocks.

    No test split is carved out here: the test data comes from its own disjoint
    pulse window, loaded separately.

    Every record at a given tile_pulse -- including the same tile in another
    polarization -- lands on the same side, so a background's clean eigenvalue
    floor cannot appear in both. A buffer of pulse tiles is discarded at the
    boundary so the two sides are not immediate spatial neighbours.

    Args:
        groups (np.ndarray): (N,) tile_pulse of each record.
        val_frac (float): fraction of the pulse-tile axis held out for val.
        buffer_tiles (int): pulse tiles dropped at the boundary.

    Returns:
        idx_train, idx_val (np.ndarray of int)
    """
    uniq = np.unique(groups)          # sorted ascending
    n = len(uniq)

    n_val = int(round(val_frac * n))
    n_train = n - n_val
    if n_train <= 0 or n_val <= 0:
        raise ValueError(f'Not enough distinct pulse tiles ({n}) to split')

    train_g = uniq[:n_train]
    val_g = uniq[n_train:]

    # Drop a buffer on each side of the single internal boundary
    if buffer_tiles > 0:
        if len(train_g) > buffer_tiles:
            train_g = train_g[:-buffer_tiles]
        if len(val_g) > buffer_tiles:
            val_g = val_g[buffer_tiles:]

    idx_train = np.where(np.isin(groups, train_g))[0]
    idx_val = np.where(np.isin(groups, val_g))[0]

    print(f"\n  Train/val block split on tile_pulse (buffer={buffer_tiles} pulse tiles):")
    print(f"    train pulses [{train_g.min()}, {train_g.max()}] -> {len(idx_train)} tiles")
    print(f"    val   pulses [{val_g.min()}, {val_g.max()}] -> {len(idx_val)} tiles")

    return idx_train, idx_val


def load_paired_test_dir(test_dir, tag=''):
    """
    Load a PAIRED mountain test set written by
    generate_mountain_rfi_data.py --paired-test.

    Each channel file holds exactly two rows per source tile: one untouched
    (label 0) and one forced-contaminated (label >= 1), sharing a pair_id.
    This function splits each file into its clean and contaminated halves and
    sorts both by pair_id, so array index i refers to the SAME background
    tile under both conditions -- which is what lets the "examine the
    behavior" check compare predictions (and the diagonal jump metric) on a
    like-for-like basis instead of across two unrelated tiles.

    Args:
        test_dir (str): directory of mountain_rfi_data_paired_<freq>_<pol>.h5 files.
        tag (str): label used in the printout.

    Returns:
        dict with 'clean', 'contam' (each a dict of eigen/global/labels/
        channels/diagonal/diag_valid_idx[/jsr]) and 'meta'.
    """
    paths = sorted(glob.glob(os.path.join(test_dir, PAIRED_FILE_PATTERN)))
    if not paths:
        raise FileNotFoundError(f"No {PAIRED_FILE_PATTERN} files found in {test_dir}")

    def empty_side():
        return {'eigen': [], 'global': [], 'labels': [], 'channels': [],
                'diagonal': [], 'diag_valid_idx': [], 'jsr': []}

    clean, contam = empty_side(), empty_side()
    meta = {'dir': test_dir, 'files': [], 'channels': []}

    print(f"\nLoading {tag or test_dir} (paired test) ...")

    for path in paths:
        with h5py.File(path, 'r') as f:
            if not bool(f.attrs.get('paired_test', False)):
                print(f"    WARNING: {os.path.basename(path)} does not have "
                      f"paired_test=True; skipping")
                continue

            freq = str(f.attrs.get('frequency', '?'))
            pol = str(f.attrs.get('polarization', '?'))
            chan = f'{freq}-{pol}'

            if 'diagonal' not in f or 'diag_valid_idx' not in f:
                raise ValueError(
                    f"{path} has no 'diagonal'/'diag_valid_idx' dataset. "
                    f"Regenerate it with the current generate_mountain_rfi_data.py, "
                    f"which writes these."
                )

            labels = f['labels'][:].astype(np.int32)
            pair_id = f['pair_id'][:].astype(np.int64)
            eigvals = f['eigenvalues'][:]
            diag = np.asarray(f['diagonal'][:], dtype=np.float64)
            diag_valid = np.asarray(f['diag_valid_idx'][:], dtype=bool)
            jsr = np.asarray(f['jsr_db'][:], dtype=np.float32) if 'jsr_db' in f else None

            is_clean = (labels == 0)
            is_contam = ~is_clean

            order_clean = np.argsort(pair_id[is_clean])
            order_contam = np.argsort(pair_id[is_contam])
            pid_clean = pair_id[is_clean][order_clean]
            pid_contam = pair_id[is_contam][order_contam]

            if not np.array_equal(pid_clean, pid_contam):
                common = np.intersect1d(pid_clean, pid_contam)
                print(f"    NOTE: {os.path.basename(path)} pair_id mismatch "
                      f"(clean={len(pid_clean)}, contam={len(pid_contam)}); "
                      f"using {len(common)} matched pairs")
                order_clean = order_clean[np.isin(pid_clean, common)]
                order_contam = order_contam[np.isin(pid_contam, common)]

            idx_clean = np.where(is_clean)[0][order_clean]
            idx_contam = np.where(is_contam)[0][order_contam]

            eigen_c, global_c = features_from_eigenvalues(eigvals[idx_clean])
            eigen_x, global_x = features_from_eigenvalues(eigvals[idx_contam])

            clean['eigen'].append(eigen_c)
            clean['global'].append(global_c)
            clean['labels'].append(labels[idx_clean])
            clean['channels'].append(np.full(len(idx_clean), chan, dtype=object))
            contam['eigen'].append(eigen_x)
            contam['global'].append(global_x)
            contam['labels'].append(labels[idx_contam])
            contam['channels'].append(np.full(len(idx_contam), chan, dtype=object))

            clean['diagonal'].append(diag[idx_clean])
            clean['diag_valid_idx'].append(diag_valid[idx_clean])
            contam['diagonal'].append(diag[idx_contam])
            contam['diag_valid_idx'].append(diag_valid[idx_contam])

            if jsr is not None:
                contam['jsr'].append(jsr[idx_contam])

            meta['files'].append(os.path.basename(path))
            if chan not in meta['channels']:
                meta['channels'].append(chan)

            print(f"  {os.path.basename(path)}: {len(idx_clean)} matched pairs  [{chan}]")

    def finalize(side):
        out = {
            'eigen': np.concatenate(side['eigen'], axis=0),
            'global': np.concatenate(side['global'], axis=0),
            'labels': np.concatenate(side['labels'], axis=0),
            'channels': np.concatenate(side['channels'], axis=0),
            'diagonal': np.concatenate(side['diagonal'], axis=0).astype(np.float32),
            'diag_valid_idx': np.concatenate(side['diag_valid_idx'], axis=0),
        }
        out['jsr'] = np.concatenate(side['jsr'], axis=0) if side.get('jsr') else None
        return out

    return {'clean': finalize(clean), 'contam': finalize(contam), 'meta': meta}


