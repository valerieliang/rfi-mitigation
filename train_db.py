"""
train_db.py

Training pipeline for the CNN-based RFI knee-index classifier.

Consumes the tile records written by generate_amazon_data.py (real Amazon
background, rfi_data_<freq>_<pol>.h5) and generate_mountain_rfi_data.py (real
mountain background, mountain_rfi_data_<freq>_<pol>.h5). Both file families
share the same per-tile schema -- labels, eigenvalues, and (since both
generators were updated to store it) the SCM diagonal and its per-index
validity mask -- so they load through the same function and train as one
combined pool. The SCM was already gap-excluded at generation time and its
eigenvalues stored in LINEAR scale, so this script never touches a complex
CPI tile -- it truncates, normalizes, and trains.

Standard CPI dimensions: 16 pulses x 250 range samples (M=16, K=250).

Data layout: combined training pool, two kinds of held-out test
-----------------------------------------------------------------
--data-dir accepts ONE OR MORE directories and concatenates everything found
in them into a single train+val pool (default: an Amazon run and a mountain
run together):

    --data-dir data/amazon_train data/mountain_rfi_train   -> train + val

Tiles from different directories can share a numeric tile_pulse by pure
coincidence (they are different granules / physical locations), so each
directory is folded into the train/val split key with its own offset --
see load_rfi_data_dir -- to guarantee a background from one source never ends
up split across train and val because of a coincidental index collision with
another source.

Two, independent kinds of held-out evaluation follow training:

  1. --test-dir: the ORIGINAL design. A disjoint pulse window, generated
     separately (same 0..6 band range, clean interspersed at random), so no
     test tile shares a background with training. Evaluated with the existing
     CHECK 1 / CHECK 2 (clean_check / contaminated_check) machinery.

  2. --paired-test-dir: a NEW, stronger check, generated by
     generate_mountain_rfi_data.py --paired-test. For every confirmed-clean
     mountain tile, that run writes BOTH an untouched copy and a
     forced-contaminated copy of the IDENTICAL raw CPI (see that script's
     docstring). Because both halves of a pair share one background, this
     script can directly compare model behavior on the same tile clean vs.
     RFI-overlaid, rather than across two different tiles that merely drew
     different band counts. This is the "examine the behavior" check.

     It also reports a non-ML companion signal: the SCM-diagonal jump metric.
     RFI raises the diagonal power sharply on the row(s) it occupies, so a
     contaminated tile's diagonal has a large step between an injected row
     and its clean neighbors, while a clean tile's diagonal stays
     comparatively flat. diagonal_jump_metric() computes the largest
     adjacent-row jump (dB) over the valid diagonal entries, and the paired
     check reports how well a simple percentile threshold on that jump alone
     -- no model involved -- separates clean from contaminated. The same
     metric is also reported at the population level (clean vs contaminated
     tiles, not necessarily paired) on --test-dir, whenever that data has a
     diagonal stored.

Generating the disjoint --test-dir region (use a seed distinct from the
training run, so the held-out injections are an independent realization):

    py-isce3 generate_amazon_data.py granule.h5 --freq A \\
        --pulse-start 888222 --pulse-end 896222 \\
        --range-start 2000 --range-end 25000 \\
        --compute-subswath-mask \\
        --off-diag-overlap-ratio 0.03 --diag-valid-ratio 0.02 \\
        --seed 7 --output-dir data/rfi_test

Generating the paired mountain test region:

    python generate_mountain_rfi_data.py clean_mountains_filtered.h5 granule.h5 \\
        --paired-test --max-bands 6 --mask-mode subswath \\
        --seed 7 --output-dir data/mountain_rfi_paired_test

Design decisions
----------------
1. The generating run is expected to have used very permissive gap-exclusion
   validity ratios (3% off-diagonal overlap, 2% diagonal valid) so dithered
   CPIs are preserved rather than dropped. That trades some SCM estimate
   quality for data yield; the feature normalization below is what makes the
   trade-off usable. The ratios actually used live in the file attrs and are
   echoed at load time, so a mismatch is visible instead of silent.
2. Eigenvalues are normalized on the LINEAR scale first (lambda_i / lambda_max,
   so lambda_max -> 1), THEN converted to dB. This removes absolute power level
   as a factor (dithered vs full-power CPIs), leaving spectral SHAPE as the
   signal the model learns from.
3. Only the first N_KEEP = 12 eigenvalues (the 12 largest, descending) are used
   as features. The remaining 4 (smallest) are the ones most exposed to
   dithering / dropout artifacts -- roughly 38.6% of healthy tiles show a
   >10 dB collapse in the smallest eigenvalue. Truncation happens BEFORE
   normalization, so a collapsed eigenvalue never reaches lambda_max, the dB
   floor, or the global features.
4. Condition number (dB) and effective rank are BOTH computed from the kept 12
   eigenvalues only, for every tile, clean or dithered alike, so the two global
   features stay on a consistent basis.

The model architecture is untouched. build_model is called with
cpi_size = N_KEEP, which only sets the length of the eigen-branch input;
n_knee_classes stays tied to the LABEL range, so truncating the features cannot
silently reshape the output head.

Feature extraction (per CPI tile)
---------------------------------
eigen_input  shape (N_KEEP, 2):
    channel 0 -- top N_KEEP eigenvalues, normalized by lambda_max on the linear
                 scale, then 10*log10 (so channel 0 always starts at 0 dB)
    channel 1 -- finite differences of channel 0 (slopes in dB per index),
                 zero-padded at index N_KEEP-1 so the tensor stays (N_KEEP, 2)

global_input shape (2,):
    0  condition_number_db -- ev_db[0] - ev_db[N_KEEP-1], over the kept 12
    1  eff_rank            -- Shannon-entropy effective rank, over the kept 12

Train / val split
-----------------
Split by CONTIGUOUS BLOCKS OF PULSE TILES, not by random row. Tiles at the same
tile_pulse in different polarizations are the same physical background, and
neighbouring tiles share clutter, so a random split would leak a background's
clean eigenvalue floor from train into val. Splitting on tile_pulse keeps every
co-located tile together; --split-buffer pulse tiles are dropped at the
boundary so the two sides are not immediate spatial neighbours.

Usage
-----
    python train_db.py \\
        --data-dir data/amazon_train data/mountain_rfi_train \\
        --test-dir data/rfi_test \\
        --paired-test-dir data/mountain_rfi_paired_test

Outputs
-------
    models/<run>/best_model.keras
    models/<run>/training_curves.png
    models/<run>/clean_check.png              -- check 1: predictions on clean tiles
    models/<run>/confusion_matrix.png         -- full 0..6 grid, clean row included
    models/<run>/metrics.png
    models/<run>/accuracy_vs_jsr.png
    models/<run>/diagonal_jump_hist_testregion.png  -- if --test-dir has a diagonal
    models/<run>/paired_behavior.png          -- if --paired-test-dir is given
    models/<run>/diagonal_jump_hist_paired.png      -- if --paired-test-dir is given
    models/<run>/eval_results.json
    models/<run>_summary.json
"""

